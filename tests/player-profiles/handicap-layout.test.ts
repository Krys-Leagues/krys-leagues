import assert from "node:assert/strict"
import { readFileSync } from "node:fs"
import test from "node:test"

const profile = readFileSync("app/players/[id]/page.tsx", "utf8")
const hero = readFileSync("components/PlayerProfileHero.tsx", "utf8")
const styles = readFileSync("app/players/[id]/page.module.css", "utf8")
const heroStyles = readFileSync("components/PlayerProfileHero.module.css", "utf8")

test("public profile passes the published Handicap summary into the existing hero", () => {
  assert.match(profile, /handicap=\{publicHandicap \? \{[\s\S]*displayIndex:[\s\S]*status:[\s\S]*qualifyingCardCount:/)
  assert.match(hero, /publicLayout && <div className=\{styles\.recognitionBand\} aria-label="HANDICAP"/)
  assert.match(hero, /handicap\?\.displayIndex/)
  assert.match(hero, /handicap\?\.unavailable/)
  assert.match(hero, /NOT YET RATED/)
  assert.doesNotMatch(hero, /styles\.handicapSummary|handicap\.status|handicap\.qualifyingCardCount/)
  assert.match(heroStyles, /\.handicapRecognition[\s\S]*\.handicapTileLabel[\s\S]*\.handicapTileValue/)
  assert.match(heroStyles, /@media[\s\S]*\.handicapRecognition[\s\S]*min-width:170px/)
})

test("profile keeps the Handicap tile separate and moves published history to the bottom", () => {
  assert.doesNotMatch(profile, /aria-label="Published Handicap"/)
  assert.match(profile, /aria-pressed=\{openProfileSection === "handicap-history"\}/)
  assert.match(profile, /aria-controls="handicap-history-panel"/)
  assert.match(profile, />HANDICAP HISTORY<\/button>/)
  assert.match(profile, /scrollIntoView\(\{ behavior: "smooth", block: "start" \}\)/)
  assert.match(profile, /className=\{styles\.courseAchievementGroups\} id="handicap-history-panel"/)
  assert.doesNotMatch(profile, /className=\{styles\.handicapHistorySection\}/)
  assert.doesNotMatch(profile, /<summary>Handicap History<\/summary>/)
  assert.match(profile, /Previous \/ new[\s\S]*Change[\s\S]*Status[\s\S]*Cards/)
  assert.match(profile, /previous === null \? "—"/)
  assert.match(profile, /className=\{styles\.handicapHelp\}/)
  assert.match(profile, /What Is a Handicap\?/)
  assert.match(profile, /aria-hidden="true">\?<\/span>/)
  assert.match(profile, /recent qualifying cards/)
  assert.doesNotMatch(profile, /all of the latest 20 qualifying scorecards|best five or best ten/)
  assert.match(profile, /negative, zero, and positive|Negative, zero, and positive/)
  assert.match(profile, /100% handicap allowance/)
  assert.match(profile, /Player A has a Handicap Index of -2\.02/)
  assert.match(profile, /Index difference is 14\.78/)
  assert.doesNotMatch(profile, /versioned reference slope 8\.515/)
  assert.match(profile, /rounding rule, or hole-by-hole allocation are not stated here/)
  assert.match(profile, /Match Handicap adjustments do not overwrite gross scores/)
  assert.doesNotMatch(styles, /\.handicapSummary|\.handicapLabel|\.handicapValue|\.handicapStatus|\.handicapUnavailable/)
  assert.match(styles, /\.handicapHistoryTableWrap[\s\S]*overflow-x: auto/)
  assert.match(styles, /\.handicapHelp[\s\S]*\.handicapHelpIcon[\s\S]*\.handicapHelpContent/)
  assert.match(styles, /\.courseAchievementGroups#handicap-history-panel[\s\S]*color: #f8fafc/)
  assert.doesNotMatch(styles, /\.handicapHistorySection\s*\{[\s\S]*background: #020617ef/)
  assert.match(styles, /\.handicapHelpExample[\s\S]*background: #000814/)
  assert.match(styles, /@media \(max-width: 640px\)[\s\S]*\.handicapHelpContent dl[\s\S]*grid-template-columns: 1fr/)
})
