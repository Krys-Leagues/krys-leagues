import assert from "node:assert/strict"
import { existsSync, readFileSync } from "node:fs"
import { test } from "node:test"

const page = readFileSync(new URL("../app/kwt/net/page.tsx", import.meta.url), "utf8")
const css = readFileSync(new URL("../app/kwt/net/page.module.css", import.meta.url), "utf8")
const rankingCss = readFileSync(new URL("../app/kwt/net/ranking.module.css", import.meta.url), "utf8")

test("KWT NET public page keeps the approved launch structure", () => {
  for (const asset of ["public/kwt/green-kiwi-sticker.png", "public/kwt/gold-kiwi-sticker.png", "public/kwt/coconut-sticker.png"]) assert.equal(existsSync(asset), true)
  assert.match(page, /<h1>KWT NET LEADERBOARD<\/h1>/)
  assert.match(page, /FIND MY KWT STROKES/)
  assert.match(page, /PLAYING HANDICAP/)
  assert.match(page, /GO TO KWT SITE — ENTER SCORES \/ VIEW GROSS/)
  assert.match(page, /PAST WEEKS/)
  assert.match(page, /SEASON NET/)
  assert.match(page, /styles\.boardControls/)
  assert.match(page, /styles\.handicapToggle/)
  assert.match(page, /Your Gross Score \+ Playing Handicap = NET Score/)
  assert.equal((page.match(/styles\.secondaryAction/g) ?? []).length, 1)
  assert.doesNotMatch(page, /styles\.primaryAction/)
  assert.match(page, /<th>EASY NET<\/th>/)
  assert.match(page, /<th>HARD NET<\/th>/)
  assert.match(page, /<th>DIVISION RANK<\/th>/)
  assert.match(page, /<th>OVERALL RANK<\/th>/)
  assert.match(page, /<th>HANDICAP<\/th>/)
  assert.match(page, /formatGolfHandicapIndex\(row\.handicapIndex\)/)
  assert.match(page, /handicapDisplay.*UNRATED/)
  assert.match(page, /row\.handicapStatus === "PROVISIONAL"/)
  assert.match(page, /rankingStyles\.divisionMedal.*aria-label/)
  assert.match(page, /gold-kiwi-sticker\.png/)
  assert.match(page, /green-kiwi-sticker\.png/)
  assert.match(page, /coconut-sticker\.png/)
  assert.match(page, /BOGEY-FREE BADGE KEY/)
  assert.match(page, /function DivisionKey/)
  assert.match(page, /Division color key/)
  assert.doesNotMatch(page, /<small className=\{divisionClass\}>/)
  assert.match(page, /ELITE[\s\S]*PRO[\s\S]*SEMI-PRO[\s\S]*AMATEUR[\s\S]*PROVISIONAL/)
  assert.ok(page.indexOf("function BadgeKey") < page.indexOf("<DivisionKey />"))
  assert.ok(page.indexOf("<DivisionKey />") < page.indexOf('<h2 id="bogey-free-badge-key">'))
  assert.match(page, /Bogey-free Easy — All 18 holes\./)
  assert.match(page, /Bogey-free Hard — All 18 holes\./)
  assert.match(page, /Bogey-free Easy \+ Hard — Both 18-hole rounds\./)
  assert.doesNotMatch(page, /🥝|🥥/)
  assert.match(page, /Bogey-free Hard round/)
  assert.match(page, /Bogey-free Easy and Hard round/)
  assert.doesNotMatch(page, /styles\.medal/)
  assert.match(page, /Loading this week's results|Waiting for this week's results/)
  assert.doesNotMatch(page, /PLAYER TOOLS/)
  assert.doesNotMatch(page, /Public result view|Course ratings, slopes|Verified NET results|No verified KWT weekend and course-rating record/)
  assert.doesNotMatch(page, /EASY GROSS|HARD GROSS|COMBINED GROSS/)
})

